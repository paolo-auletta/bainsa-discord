-- Upgrade the legacy BAINSA Discord schema to the V1 university-scoped contract.
-- This migration is intentionally additive/idempotent: legacy rows and applied
-- migration records are preserved, while old Discord resource columns are
-- renamed or backfilled into the new names.

CREATE TABLE IF NOT EXISTS schema_migrations (
  filename text PRIMARY KEY,
  checksum char(64) NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now(),
  execution_ms integer NOT NULL
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

