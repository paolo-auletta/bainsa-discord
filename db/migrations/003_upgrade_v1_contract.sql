CREATE OR REPLACE FUNCTION validate_member_division_university()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM members
    JOIN divisions
      ON divisions.id = NEW.division_id
     AND divisions.university_id = members.university_id
    WHERE members.discord_user_id = NEW.discord_user_id
  ) THEN
    RAISE EXCEPTION 'member division must belong to the member university';
  END IF;

  RETURN NEW;
END;
$$;

