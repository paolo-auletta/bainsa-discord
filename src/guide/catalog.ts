function entry({
  command,
  title,
  topic,
  summary,
  scopeKind,
  before,
  inputs,
  success,
  activity,
}) {
  return Object.freeze({
    command,
    title,
    topic,
    summary,
    scopeKind,
    before: Object.freeze(before),
    inputs: Object.freeze(inputs),
    success,
    activity,
  });
}

